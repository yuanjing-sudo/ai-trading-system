"""Quantitative analysis toolkit for the AI Trading System.

This package provides production-grade implementations of:

- ``indicators``: 120+ vectorized technical indicators
- ``alpha101``: WorldQuant 101 alpha formulas
- ``pandasta_wrapper``: 130+ pandas-ta indicators with fallback
- ``ccxt_fetcher``: Real crypto exchange data from 100+ exchanges
- ``quantstats_reports``: Performance tear sheets and risk reports
- ``factors``: cross-sectional and time-series alpha factors
- ``strategies``: composable trading strategies with risk overlays
- ``risk``: drawdown, tail-risk, and regime analytics
- ``portfolio``: mean-variance, risk-parity, and Black-Litterman optimizers
- ``backtest``: event-driven backtester with realistic execution costs
- ``optimizer``: walk-forward parameter search with purged splits
"""

